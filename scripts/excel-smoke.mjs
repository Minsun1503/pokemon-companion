import assert from 'node:assert/strict';
import {execFileSync, spawn} from 'node:child_process';
import {randomUUID} from 'node:crypto';
import {mkdtemp, rm, writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createInterface} from 'node:readline';
import {Client} from '../backend/node_modules/@modelcontextprotocol/sdk/dist/esm/client/index.js';
import {InMemoryTransport} from '../backend/node_modules/@modelcontextprotocol/sdk/dist/esm/inMemory.js';
import {createServer} from '../backend/dist/index.js';
import {PokemonRuntime} from '../backend/dist/pokemon/runtime.js';

assert.equal(process.platform, 'win32', 'Requires Windows and installed desktop Excel.');
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const scratch = await mkdtemp(resolve(tmpdir(), 'pokemon-excel-smoke-'));
const executable = resolve(scratch, 'ExcelFixture.exe');
const compile = resolve(scratch, 'compile.ps1');
const powershell = resolve(process.env.SystemRoot, 'System32/WindowsPowerShell/v1.0/powershell.exe');
const runtime = new PokemonRuntime({
  state: {pet: 'pikachu', activity: 'idle', message: '', task: '', visible: false, paused: false, completedActions: 0},
  async start() {}, async close() {}, async capture() {}, async update(patch) {Object.assign(this.state, patch);},
});
const server = createServer(runtime);
const client = new Client({name: 'excel-smoke', version: '1'});
const [ct, st] = InMemoryTransport.createLinkedPair();
let child;
let lines;
let exit;
try {
  await writeFile(compile, "param($source, $output)\n$ErrorActionPreference = 'Stop'\nAdd-Type -Path $source -ReferencedAssemblies System.Web.Extensions -OutputAssembly $output -OutputType ConsoleApplication\n");
  execFileSync(powershell, ['-NoLogo', '-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'RemoteSigned', '-File', compile, resolve(root, 'scripts/excel-smoke-fixture.cs'), executable], {windowsHide: true});
  child = spawn(executable, [scratch, randomUUID().slice(0, 8)], {windowsHide: true, stdio: ['pipe', 'pipe', 'inherit']});
  exit = new Promise(resolveExit => child.once('exit', resolveExit));
  lines = createInterface({input: child.stdout});
  const iterator = lines[Symbol.asyncIterator]();
  const receive = async () => {
    const line = await iterator.next();
    assert(!line.done, 'Excel fixture exited before reporting its result.');
    const data = JSON.parse(line.value.replace(/^\uFEFF/, ''));
    assert.notEqual(data.kind, 'error', data.error);
    return data;
  };
  const command = async name => {child.stdin.write(name + '\n'); return receive();};
  const fixture = await receive();
  assert.equal(fixture.kind, 'ready');
  await Promise.all([server.connect(st), client.connect(ct)]);
  const tools = await client.listTools();
  assert(tools.tools.some(tool => tool.name === 'excel'));
  let base = {window_id: fixture.window_a, workbook_name: fixture.name_a, sheet: 'Data'};
  const other = {window_id: fixture.window_b, workbook_name: fixture.name_b, sheet: 'Data'};
  const call = async (args, expectedError = false) => {
    const result = await client.callTool({name: 'excel', arguments: {...args, timeout_ms: 15000}});
    assert.equal(result.content.length, 1);
    assert.equal(result.content[0].type, 'text', 'No screenshots.');
    assert.equal(Boolean(result.isError), expectedError, result.content[0].text);
    assert(result.content[0].text.length <= (args.max_chars ?? 8000));
    return JSON.parse(result.content[0].text);
  };
  const inspect = await call({action: 'inspect_workbook', window_id: fixture.window_a});
  assert.equal(inspect.workbook_name, fixture.name_a);
  assert.equal(inspect.full_name, fixture.path_a);
  assert(inspect.sheets.some(sheet => sheet.name === 'Data'));
  const mismatch = await call({...base, action: 'read_range', workbook_name: fixture.name_b, range: 'A1'}, true);
  assert.equal(mismatch.input_state, 'not_sent');
  const initial = await call({...base, action: 'read_range', range: 'A1:E2'});
  assert(initial.cells.every(cell => cell.value === null));
  const data = [['00123', '=literal', 7, true, null], ['chữ 🐱', "'apostrophe", 0, false, '']];
  const written = await call({...base, action: 'write_range', range: 'A1:E2', data});
  assert.equal(written.verified, true);
  assert.equal(written.written_cells, 10);
  assert.equal(written.saved, false);
  const untouched = await call({...other, action: 'read_range', range: 'A1:E2'});
  assert(untouched.cells.every(cell => cell.value === null), 'The other active workbook must stay empty.');
  const read = await call({...base, action: 'read_range', range: 'A1:E2', page_size: 3});
  assert.deepEqual(read.cells.map(cell => cell.value), data[0].slice(0, 3));
  assert.equal(read.cells[1].formula, null, 'Leading equals sign must remain literal.');
  let cells = [...read.cells], offset = read.next_offset;
  for (;;) {
    const page = await call({...base, action: 'read_range', range: 'A1:E2', offset, version: read.version, page_size: 3});
    cells.push(...page.cells);
    if (!page.has_more) break;
    offset = page.next_offset;
  }
  assert.equal(cells.length, 10);
  assert.equal(cells[5].value, 'chữ 🐱');
  assert.equal(cells[6].value, "'apostrophe");
  assert.equal(cells[7].value, 0);
  assert.equal(cells[8].value, false);
  assert.equal(cells[9].value, '');
  const bulk = Array.from({length: 100}, (_, row) => Array.from({length: 10}, (_, col) => col === 5 ? 'needle' : row * 10 + col));
  const bulkStart = Date.now();
  const bulkWrite = await call({...base, action: 'write_range', range: 'A10:J109', data: bulk});
  assert.equal(bulkWrite.written_cells, 1000);
  assert.equal(bulkWrite.native_calls, 1);
  const bulkMilliseconds = Date.now() - bulkStart;
  const firstMatch = await call({...base, action: 'find_cells', range: 'A10:J109', query: 'needle', match: 'exact', page_size: 2});
  assert.deepEqual(firstMatch.cells.map(cell => cell.address), ['F10', 'F11']);
  const nextMatch = await call({...base, action: 'find_cells', range: 'A10:J109', query: 'needle', match: 'exact', offset: firstMatch.next_offset, version: firstMatch.version, page_size: 2});
  assert.deepEqual(nextMatch.cells.map(cell => cell.address), ['F12', 'F13']);
  const longText = '"🐱\\\n'.repeat(500);
  await call({...base, action: 'write_range', range: 'A120', data: [[longText]]});
  const shortCell = await call({...base, action: 'read_range', range: 'A120', cell_chars: 16});
  assert.equal(shortCell.cells[0].value_clipped, true);
  const fullCell = await call({...base, action: 'read_range', range: 'A120', cell_chars: 10000, max_chars: 16000});
  assert.equal(fullCell.cells[0].value, longText);
  assert.equal(fullCell.version, shortCell.version);
  const notEmpty = await call({...base, action: 'write_range', range: 'A1', data: [['overwrite']]}, true);
  assert.equal(notEmpty.input_state, 'not_sent');
  const overwriteRead = await call({...base, action: 'read_range', range: 'A1'});
  const changed = await call({...base, action: 'write_range', range: 'A1', data: [['00999']], require_empty: false, expected_version: overwriteRead.version});
  assert.equal(changed.verified, true);
  const stale = await call({...base, action: 'read_range', range: 'A1:E2', offset: 3, version: read.version}, true);
  assert.equal(stale.input_state, 'not_sent');
  const formula = await call({...base, action: 'write_range', range: 'F3', data: [['=SUM(C1:C2)']], mode: 'formulas'});
  assert.equal(formula.verified, true);
  const calculated = await call({...base, action: 'read_range', range: 'F3'});
  assert.equal(calculated.cells[0].formula, '=SUM(C1:C2)');
  assert.equal(calculated.cells[0].value, 7);
  await call({...base, action: 'write_range', range: 'H3', data: [['=1/0']], mode: 'formulas'});
  const errorCell = await call({...base, action: 'read_range', range: 'H3'});
  assert.equal(errorCell.cells[0].value.error, '#DIV/0!');
  const foundError = await call({...base, action: 'find_cells', range: 'H3', query: '#DIV/0!', match: 'exact'});
  assert.equal(foundError.cells[0].address, 'H3');
  const find = await call({...base, action: 'find_cells', range: 'A1:F3', query: 'chữ', match: 'contains'});
  assert.equal(find.cells[0].address, 'A2');
  const findFormula = await call({...base, action: 'find_cells', range: 'A1:F3', query: 'SUM', look_in: 'formulas'});
  assert.equal(findFormula.cells[0].address, 'F3');
  await command('protect');
  const protectedWrite = await call({...base, action: 'write_range', range: 'H1', data: [[1]]}, true);
  assert.equal(protectedWrite.input_state, 'not_sent');
  await command('unprotect');
  await command('merge');
  const merged = await call({...base, action: 'write_range', range: 'F1:G1', data: [[1, 2]]}, true);
  assert.equal(merged.input_state, 'not_sent');
  await command('unmerge');
  await command('array');
  const arrayRead = await call({...base, action: 'read_range', range: 'I1:I2'});
  const arrayWrite = await call({...base, action: 'write_range', range: 'I1:I2', data: [[1], [2]], require_empty: false, expected_version: arrayRead.version}, true);
  assert.equal(arrayWrite.input_state, 'not_sent');
  await command('spill');
  const spillRead = await call({...base, action: 'read_range', range: 'J1:J2'});
  const spillWrite = await call({...base, action: 'write_range', range: 'J1:J2', data: [[1], [2]], require_empty: false, expected_version: spillRead.version}, true);
  assert.equal(spillWrite.input_state, 'not_sent');
  await command('other');
  const selected = await call({...base, action: 'select_range', range: 'B2:C2'});
  assert.equal(selected.verified, true);
  const badPath = await call({action: 'save_workbook', window_id: base.window_id, workbook_name: base.workbook_name, expected_path: fixture.path_b}, true);
  assert.equal(badPath.input_state, 'not_sent');
  const saved = await call({action: 'save_workbook', window_id: base.window_id, workbook_name: base.workbook_name, expected_path: fixture.path_a});
  assert.equal(saved.saved, true);
  await command('close_a');
  const reopened = await command('reopen');
  base = {...base, window_id: reopened.window_a};
  const persisted = await call({...base, action: 'read_range', range: 'A1'});
  assert.equal(persisted.cells[0].value, '00999');
  await command('close_a');
  const readonly = await command('reopen_readonly');
  base = {...base, window_id: readonly.window_a};
  const readonlyInfo = await call({action: 'inspect_workbook', window_id: base.window_id});
  assert.equal(readonlyInfo.read_only, true);
  const readonlyWrite = await call({...base, action: 'write_range', range: 'A121', data: [[1]]}, true);
  assert.equal(readonlyWrite.input_state, 'not_sent');
  console.log(`PASS: all six desktop Excel APIs through MCP; exact window/workbook binding, literal text, zeros/blanks, 1000-cell bulk write in ${bulkMilliseconds} ms (one native request), versioned pages, long-cell clipping, formulas/errors, bounded finding, protection/merge/array/spill/read-only rejection, verified selection, and saved file reopened; no screenshots.`);
} finally {
  await client.close();
  await server.close();
  await runtime.close();
  if (child) {child.stdin.end('close\n'); await exit; lines.close();}
  assert.equal(dirname(scratch), resolve(tmpdir()), 'Refuse cleanup outside the owned temporary folder.');
  await rm(scratch, {recursive: true, force: true});
}
